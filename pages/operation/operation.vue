		// 组装树结构：根 -> 分组(多级) -> 站点叶子节点
		buildTree(type, rootGroup, groups, stations) {
			const root = {
				id: rootGroup && rootGroup.id !== undefined ? rootGroup.id : null,
				name: (rootGroup && rootGroup.name) || '',
				key: 'root',
				expanded: true, // 默认展开根
				children: []
			};

			// 建立分组节点（保留接口返回顺序）
			const groupMap = {};
			groups.forEach(g => {
				groupMap[String(g.id)] = {
					key: 'group-' + g.id,
					id: g.id,
					name: g.name || '',
					children: [],
					expanded: true // 默认展开分组
				};
			});
			// 通过每个分组的id和parentId判断父子分组节点：分组的parentId匹配到某个分组id则挂为其子分组；
			//    匹配不到（parentId === 0 或父分组不在列表中），则作为根分组的子分组
			const attached = {};
			groups.forEach(g => {
				const gid = String(g.id);
				const pid = String(g.parentId);
				const parent = groupMap[pid];
				if (parent && pid !== gid && !attached[gid]) {
					parent.children.push(groupMap[gid]);
					attached[gid] = true;
				}
			});
			groups.forEach(g => {
				if (!attached[String(g.id)]) {
					root.children.push(groupMap[String(g.id)]);
				}
			});

			// 站点叶子节点：按类型分类后挂到对应分组下（分组不存在则挂到根下）
			stations.forEach(s => {
				const info = this.getStationLeafType(type, s);
				if (!info) return;
				const node = {
					key: 'station-' + s.id,
					id: s.id,
					name: s.name || '',
					children: [],
					isStation: true,
					lightCount: s.light || 0, // 单灯数量字段light
					icon: this.getStationIcon(s, info.folder, info.isWater),
					// 用于跳转到站点详情界面
					stationType: s.stationType,
					supplyMode: s.supplyMode,
					hasLight: s.hasLight,
					hasPower: s.hasPower
				};
				const group = groupMap[String(s.groupId)];
				if (group) {
					group.children.push(node);
				} else {
					root.children.push(node);
				}
			});

			return root;
		},
		// 站点叶子类型判断（返回 null 表示该站点不在此标签页展示）
		getStationLeafType(type, station) {
			if (type === 'light') {
				// 单灯界面最小子节点：stationType == 3 || hasLight == true
				if (station.stationType === 3 || station.hasLight) {
					return { folder: 'lightStatus', isWater: false };
				}
				return null;
			}
			// 配电箱界面：水浸/单灯/配电箱/隧道/箱变/太阳能灯杆
			if (station.stationType === 4 && station.supplyMode === 1) {
				return { folder: 'waterStatus', isWater: true }; // 水浸
			}
			if (station.stationType === 3 && station.hasLight && !station.hasPower) {
				return { folder: 'lightStatus', isWater: false }; // 单灯
			}
			if (station.stationType === 2) {
				return { folder: 'tunnelStatus', isWater: false }; // 隧道
			}
			if (station.stationType === 1 && station.supplyMode === 2) {
				return { folder: 'boxStationStatus', isWater: false }; // 箱变
			}
			if ((station.stationType === 1 || station.type === 1) && station.supplyMode === 1) {
				return { folder: 'powerboxStatus', isWater: false }; // 配电箱
			}
			if (station.stationType === 5) {
				return { folder: 'solarStatus', isWater: false }; // 太阳能灯杆
			}
			return null;
		},
		// 根据站点状态计算叶子节点状态图标路径
		getStationIcon(station, folder, isWater) {
			const base = '/static/operation/' + folder + '/';
			if (isWater) {
				// 水浸：离线 / 正常 / 报警
				if (!station.online) return base + 'offline.png';
				return station.alarm ? base + 'warning.png' : base + 'normal.png';
			}
			// 单灯、配电箱、隧道、箱变、太阳能灯杆：离线 / 开灯报警 / 开灯 / 关灯报警 / 关灯
			if (!station.online) return base + 'offline.png';
			if (station.running && station.alarm) return base + 'turn-on-alarm.png';
			if (station.running) return base + 'turn-on.png';
			if (station.alarm) return base + 'turn-off-alarm.png';
			return base + 'turn-off.png';
		}
	}
}
