			const weekNames = ['星期一', '星期二', '星期三', '星期四', '星期五', '星期六', '星期日'];
			const weekMap = {};
			(weeks || []).forEach(item => {
				const week = Number(item.week);
				if (!week || week < 1 || week > 7) return;
				if (!weekMap[week]) {
					weekMap[week] = {};
				}
				weekMap[week][item.am ? 'am' : 'pm'] = item.enable === true || item.enable === 'true' || item.enable === 1;
			});

			return weekNames.map((weekName, index) => {
				const week = index + 1;
				const day = weekMap[week] || {};
				return {
					weekName: weekName,
					items: [
						{ label: '上午', enable: day.am !== undefined ? day.am : false },
						{ label: '下午', enable: day.pm !== undefined ? day.pm : false }
					]
				};
			});
