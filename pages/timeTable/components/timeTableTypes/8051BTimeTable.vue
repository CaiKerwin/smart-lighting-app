			timeTableId: null,
			// 时间表名称
			timeTableName: '',
			// 详情中的全年内容
			content: {},
			// 详情加载状态
			loading: false,
			loadError: false,
			// 星期卡片数据
			weekData: []
		};
	},
	computed: {
		// 获取当前月份的天数数组以及每一天处理好的数据
		currentMonthDays() {
			const monthData = this.content[this.currentMonth] || {};
			const dayKeys = Object.keys(monthData).map(Number).sort((a, b) => a - b);

			// 该月没有任何数据时返回空数组，展示空状态
			if (dayKeys.length === 0) {
				return [];
			}

			// 按接口实际返回的日期键渲染，避免个别日期缺失时卡片错位
			return dayKeys.map((day) => ({
				day: day,
				items: this.parseDayData(monthData[day])
			}));
		},
		// 占位卡片数量：让 3 列网格的最后一行保持整齐
		fillerCount() {
			const len = this.currentMonthDays.length;
			return len % 3 === 0 ? 0 : 3 - (len % 3);
		}
	},
	onLoad(options) {
		this.timeTableId = options && options.id ? Number(options.id) : null;
		if (options && options.name) {
			try {
				this.timeTableName = decodeURIComponent(options.name);
			} catch (e) {
				this.timeTableName = options.name;
			}
		}

		if (!this.timeTableId) {
			this.loading = false;
			this.loadError = true;
			return;
		}

		// 编辑页保存成功后，刷新本页详情
		this.refreshHandler = (payload) => {
			if (payload && payload.id === this.timeTableId) {
				this.get8051BTimeTableDetail();
			}
		};
		uni.$on('8051BTimeTableUpdated', this.refreshHandler);

		this.get8051BTimeTableDetail();
	},
	onUnload() {
		if (this.refreshHandler) {
			uni.$off('8051BTimeTableUpdated', this.refreshHandler);
			this.refreshHandler = null;
		}
	},
	methods: {
		// 切换月份
		selectMonth(month) {
			this.currentMonth = month;
		},

		// 某月是否存在时间表数据
		hasMonthData(month) {
			return Object.keys(this.content[month] || {}).length > 0;
		},
		// 解析某一天的数据，把 o1~o4、c1~c4、a1~a4 转换成 UI 数组格式
		// a值：1启用 2禁用，o-c 表示对应的启用或者禁用时间段
		parseDayData(dayData) {
			if (!dayData) return [];
			const items = [];
			for (let i = 1; i <= 4; i++) {
				const openVal = dayData[`o${i}`];
				const closeVal = dayData[`c${i}`];
				const actionVal = dayData[`a${i}`];
				if (openVal === undefined || openVal === null || openVal === '') continue;
				if (closeVal === undefined || closeVal === null || closeVal === '') continue;
				if (actionVal === undefined || actionVal === null || actionVal === '') continue;

				const actionKey = Number(actionVal);
				let status = '禁用';
				let statusKey = 'deny';
				if (actionKey === 1) {
					status = '启用';
					statusKey = 'allow';
				}

				items.push({
					index: i,
					time1: String(openVal),
					time2: String(closeVal),
					status: status,
					statusKey: statusKey
				});
			}
			return items;
		},

		// 解析 extra.weeks，生成星期卡片数据
		// week 1-7 表示星期一到星期日 am=true 上午 am=false 下午 enable=true 允许 enable=false 禁止
